-- ExcelLab · Esquema de base de datos (PostgreSQL / Neon)

DROP TABLE IF EXISTS settings, activity_log, notifications, student_achievements, achievements,
  lesson_progress, student_progress, assessment_attempts, assessment_questions, assessments,
  case_submissions, practical_cases, challenge_attempts, challenges, exercise_attempts,
  exercise_options, exercises, lessons, modules, password_resets, users, roles CASCADE;

CREATE TABLE roles (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(30) NOT NULL UNIQUE,
  label VARCHAR(60) NOT NULL
);

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id SMALLINT NOT NULL,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  must_change_password SMALLINT NOT NULL DEFAULT 1,
  failed_attempts SMALLINT NOT NULL DEFAULT 0,
  locked_until TIMESTAMP NULL,
  last_login_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- se actualiza desde el código
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);
CREATE INDEX idx_users_role ON users (role_id);
CREATE INDEX idx_users_status ON users (status);

CREATE TABLE password_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  token_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  used_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pr_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_pr_token ON password_resets (token_hash);

CREATE TABLE modules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  description TEXT NULL,
  icon VARCHAR(40) NOT NULL DEFAULT 'bi-table',
  position SMALLINT NOT NULL DEFAULT 1,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP -- se actualiza desde el código
);
CREATE INDEX idx_modules_status ON modules (status, position);

CREATE TABLE lessons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id INTEGER NOT NULL,
  title VARCHAR(150) NOT NULL,
  description VARCHAR(300) NULL,
  theory TEXT NULL,
  example TEXT NULL,
  example_data TEXT NULL, -- JSON: {headers:[],rows:[[]]}
  image_url VARCHAR(255) NULL,
  position SMALLINT NOT NULL DEFAULT 1,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- se actualiza desde el código
  CONSTRAINT fk_lessons_module FOREIGN KEY (module_id) REFERENCES modules(id)
);
CREATE INDEX idx_lessons_module ON lessons (module_id, position);
CREATE INDEX idx_lessons_status ON lessons (status);

CREATE TABLE exercises (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id INTEGER NOT NULL,
  lesson_id INTEGER NULL,
  title VARCHAR(150) NOT NULL,
  topic VARCHAR(100) NOT NULL,
  difficulty VARCHAR(12) NOT NULL DEFAULT 'basico' CHECK (difficulty IN ('basico','intermedio','avanzado')),
  type VARCHAR(20) NOT NULL CHECK (type IN ('multiple_choice','true_false','complete_formula','identify_function','solve_operation','analyze_table','practical')),
  statement TEXT NOT NULL,
  instructions TEXT NULL,
  data_json TEXT NULL, -- JSON: {headers:[],rows:[[]]}
  answer_kind VARCHAR(10) NOT NULL DEFAULT 'option' CHECK (answer_kind IN ('option','number','formula','text')),
  correct_answer VARCHAR(500) NULL, -- Alternativas separadas por ||
  tolerance DECIMAL(10,4) NOT NULL DEFAULT 0.0100,
  explanation TEXT NULL,
  points SMALLINT NOT NULL DEFAULT 10,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- se actualiza desde el código
  CONSTRAINT fk_ex_module FOREIGN KEY (module_id) REFERENCES modules(id),
  CONSTRAINT fk_ex_lesson FOREIGN KEY (lesson_id) REFERENCES lessons(id)
);
CREATE INDEX idx_ex_module ON exercises (module_id);
CREATE INDEX idx_ex_lesson ON exercises (lesson_id);
CREATE INDEX idx_ex_filter ON exercises (status, difficulty, type);

CREATE TABLE exercise_options (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exercise_id INTEGER NOT NULL,
  label VARCHAR(400) NOT NULL,
  is_correct SMALLINT NOT NULL DEFAULT 0,
  position SMALLINT NOT NULL DEFAULT 1,
  CONSTRAINT fk_opt_ex FOREIGN KEY (exercise_id) REFERENCES exercises(id)
);
CREATE INDEX idx_opt_ex ON exercise_options (exercise_id);

CREATE TABLE exercise_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exercise_id INTEGER NOT NULL,
  student_id INTEGER NOT NULL,
  context VARCHAR(10) NOT NULL DEFAULT 'lab' CHECK (context IN ('lesson','lab')),
  answer VARCHAR(500) NOT NULL,
  is_correct SMALLINT NOT NULL DEFAULT 0,
  points SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ea_ex FOREIGN KEY (exercise_id) REFERENCES exercises(id),
  CONSTRAINT fk_ea_student FOREIGN KEY (student_id) REFERENCES users(id)
);
CREATE INDEX idx_ea_student ON exercise_attempts (student_id, exercise_id);
CREATE INDEX idx_ea_date ON exercise_attempts (created_at);

CREATE TABLE challenges (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  difficulty VARCHAR(12) NOT NULL DEFAULT 'basico' CHECK (difficulty IN ('basico','intermedio','avanzado')),
  situation TEXT NOT NULL,
  objective VARCHAR(300) NOT NULL,
  data_json TEXT NULL,
  instructions TEXT NULL,
  est_minutes SMALLINT NOT NULL DEFAULT 10,
  points SMALLINT NOT NULL DEFAULT 30,
  answer_kind VARCHAR(10) NOT NULL DEFAULT 'number' CHECK (answer_kind IN ('number','text','formula')),
  correct_answer VARCHAR(500) NOT NULL,
  tolerance DECIMAL(10,4) NOT NULL DEFAULT 0.0100,
  hint VARCHAR(300) NULL,
  feedback_ok VARCHAR(400) NULL,
  feedback_fail VARCHAR(400) NULL,
  position SMALLINT NOT NULL DEFAULT 1,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP -- se actualiza desde el código
);
CREATE INDEX idx_ch_filter ON challenges (status, difficulty, position);

CREATE TABLE challenge_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge_id INTEGER NOT NULL,
  student_id INTEGER NOT NULL,
  answer VARCHAR(500) NOT NULL,
  is_correct SMALLINT NOT NULL DEFAULT 0,
  points SMALLINT NOT NULL DEFAULT 0,
  seconds_spent INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_cha_ch FOREIGN KEY (challenge_id) REFERENCES challenges(id),
  CONSTRAINT fk_cha_student FOREIGN KEY (student_id) REFERENCES users(id)
);
CREATE INDEX idx_cha_student ON challenge_attempts (student_id, challenge_id);

CREATE TABLE practical_cases (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category VARCHAR(30) NOT NULL CHECK (category IN ('Administración','Ventas','Inventario','Recursos Humanos','Educación')),
  title VARCHAR(150) NOT NULL,
  context TEXT NOT NULL,
  problem TEXT NOT NULL,
  data_json TEXT NULL,
  instructions TEXT NULL,
  criteria TEXT NULL,
  mode VARCHAR(10) NOT NULL DEFAULT 'platform' CHECK (mode IN ('platform','file')),
  questions_json TEXT NULL, -- JSON: [{label,answer,kind,tolerance}]
  points SMALLINT NOT NULL DEFAULT 50,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP -- se actualiza desde el código
);
CREATE INDEX idx_pc_filter ON practical_cases (status, category);

CREATE TABLE case_submissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id INTEGER NOT NULL,
  student_id INTEGER NOT NULL,
  answers_json TEXT NULL,
  file_path VARCHAR(255) NULL,
  original_name VARCHAR(255) NULL,
  score DECIMAL(6,2) NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','reviewed')),
  feedback TEXT NULL,
  reviewed_by INTEGER NULL,
  reviewed_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- se actualiza desde el código
  CONSTRAINT fk_cs_case FOREIGN KEY (case_id) REFERENCES practical_cases(id),
  CONSTRAINT fk_cs_student FOREIGN KEY (student_id) REFERENCES users(id),
  CONSTRAINT fk_cs_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id)
);
CREATE INDEX idx_cs_student ON case_submissions (student_id, case_id);
CREATE INDEX idx_cs_status ON case_submissions (status);

CREATE TABLE assessments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id INTEGER NULL,
  title VARCHAR(150) NOT NULL,
  description TEXT NULL,
  time_limit_min SMALLINT NOT NULL DEFAULT 20,
  pass_percent SMALLINT NOT NULL DEFAULT 60,
  questions_per_attempt SMALLINT NOT NULL DEFAULT 0, -- 0 = todas
  randomize SMALLINT NOT NULL DEFAULT 1,
  max_attempts SMALLINT NOT NULL DEFAULT 0, -- 0 = ilimitados
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- se actualiza desde el código
  CONSTRAINT fk_as_module FOREIGN KEY (module_id) REFERENCES modules(id)
);
CREATE INDEX idx_as_module ON assessments (module_id);
CREATE INDEX idx_as_status ON assessments (status);

CREATE TABLE assessment_questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id INTEGER NOT NULL,
  exercise_id INTEGER NOT NULL,
  position SMALLINT NOT NULL DEFAULT 1,
  CONSTRAINT uq_aq UNIQUE (assessment_id, exercise_id),
  CONSTRAINT fk_aq_as FOREIGN KEY (assessment_id) REFERENCES assessments(id),
  CONSTRAINT fk_aq_ex FOREIGN KEY (exercise_id) REFERENCES exercises(id)
);

CREATE TABLE assessment_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id INTEGER NOT NULL,
  student_id INTEGER NOT NULL,
  question_ids TEXT NOT NULL, -- JSON con el orden de preguntas sorteadas
  answers_json TEXT NULL,
  score SMALLINT NOT NULL DEFAULT 0,
  max_score SMALLINT NOT NULL DEFAULT 0,
  percent DECIMAL(5,2) NOT NULL DEFAULT 0,
  passed SMALLINT NOT NULL DEFAULT 0,
  started_at TIMESTAMP NOT NULL,
  finished_at TIMESTAMP NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress','finished','expired')),
  CONSTRAINT fk_aa_as FOREIGN KEY (assessment_id) REFERENCES assessments(id),
  CONSTRAINT fk_aa_student FOREIGN KEY (student_id) REFERENCES users(id)
);
CREATE INDEX idx_aa_student ON assessment_attempts (student_id, assessment_id);
CREATE INDEX idx_aa_status ON assessment_attempts (status);

CREATE TABLE student_progress (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL,
  module_id INTEGER NOT NULL,
  lessons_total SMALLINT NOT NULL DEFAULT 0,
  lessons_done SMALLINT NOT NULL DEFAULT 0,
  percent DECIMAL(5,2) NOT NULL DEFAULT 0,
  completed_at TIMESTAMP NULL,
  certificate_code VARCHAR(20) NULL UNIQUE,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- se actualiza desde el código
  CONSTRAINT uq_sp UNIQUE (student_id, module_id),
  CONSTRAINT fk_sp_student FOREIGN KEY (student_id) REFERENCES users(id),
  CONSTRAINT fk_sp_module FOREIGN KEY (module_id) REFERENCES modules(id)
);

CREATE TABLE lesson_progress (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL,
  lesson_id INTEGER NOT NULL,
  completed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_lp UNIQUE (student_id, lesson_id),
  CONSTRAINT fk_lp_student FOREIGN KEY (student_id) REFERENCES users(id),
  CONSTRAINT fk_lp_lesson FOREIGN KEY (lesson_id) REFERENCES lessons(id)
);

CREATE TABLE achievements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  description VARCHAR(250) NOT NULL,
  icon VARCHAR(40) NOT NULL DEFAULT 'bi-award',
  metric VARCHAR(15) NOT NULL CHECK (metric IN ('lessons','exercises','challenges','points','modules','assessments','cases')),
  threshold INTEGER NOT NULL DEFAULT 1,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE student_achievements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL,
  achievement_id INTEGER NOT NULL,
  awarded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_sa UNIQUE (student_id, achievement_id),
  CONSTRAINT fk_sa_student FOREIGN KEY (student_id) REFERENCES users(id),
  CONSTRAINT fk_sa_ach FOREIGN KEY (achievement_id) REFERENCES achievements(id)
);

CREATE TABLE notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  title VARCHAR(150) NOT NULL,
  message VARCHAR(400) NULL,
  link VARCHAR(200) NULL,
  is_read SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_n_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_n_user ON notifications (user_id, is_read, created_at);

CREATE TABLE activity_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NULL,
  action VARCHAR(50) NOT NULL,
  entity VARCHAR(50) NULL,
  entity_id INTEGER NULL,
  detail VARCHAR(500) NULL,
  ip VARCHAR(45) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_al_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_al_user ON activity_log (user_id, created_at);
CREATE INDEX idx_al_action ON activity_log (action);

CREATE TABLE settings (
  skey VARCHAR(60) PRIMARY KEY,
  svalue VARCHAR(255) NOT NULL
);
